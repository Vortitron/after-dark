#!/usr/bin/env python3
"""einstein2c.py - EINSTEIN.AD's chalk (all/art/einstein/index.json, a stroke
font plus its lines and equations) as a C++ header for ad_einstein.cpp:

    python3 einstein2c.py all/art/einstein -o esphome/components/after_dark/ad_art_einstein.h

Only the glyphs the strings use are kept, with a-z (the wrong letters) and S
(for the '$' made from it).
"""
import argparse, json, os

ap = argparse.ArgumentParser()
ap.add_argument('art')
ap.add_argument('-o', '--out', required=True)
a = ap.parse_args()
d = json.load(open(os.path.join(a.art, 'index.json')))
g = d['glyphs']
strings = d['equations'] + d['lines']
want = {ord(c) for s in strings for c in s} | set(range(97, 123)) | {32, 83}
codes = sorted(int(k) for k in g if int(k) in want)
assert all(c < 256 for c in codes)
steps, rows = [], []
for c in codes:
    v = g[str(c)]
    assert -128 <= v['top'] < 128 and 0 <= v['advance'] < 256
    rows.append('  {%d, %d, %d, %d, %d}' % (c, v['top'], v['advance'], len(steps) // 2, len(v['steps']) // 2))
    steps += v['steps']
assert all(-128 <= s < 128 for s in steps)

def cstr(s):
    out = ''
    for ch in s:
        o = ord(ch)
        assert o < 256
        out += ch if 32 <= o < 127 and ch not in '"\\?' else '\\%03o' % o
    return '"%s"' % out

def block(vals, per=24):
    return ',\n'.join('  ' + ', '.join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per))

with open(a.out, 'w') as f:
    f.write('// Generated by einstein2c.py from %s - do not edit.\n' % os.path.normpath(a.art))
    f.write('// %d glyphs, %d bytes of pen steps, %d equations, %d lines.\n'
            % (len(codes), len(steps), len(d['equations']), len(d['lines'])))
    f.write('#pragma once\n#include <cstdint>\n\nnamespace adcore {\nnamespace art_einstein {\n\n')
    f.write('/* A glyph: its character code, the pen\'s first y (above the baseline is\n'
            '   negative), the advance, and `count` steps of (dx, dy) from STEPS + first;\n'
            '   a step longer than a pixel lifts the pen. */\n')
    f.write('struct Glyph {\n  uint8_t code;\n  int8_t top;\n  uint8_t advance;\n  uint16_t first, count;\n};\n\n')
    f.write('static const int8_t STEPS[] = {\n%s\n};\n\n' % block(steps))
    f.write('static const Glyph GLYPHS[] = {\n%s\n};\nstatic const int GLYPH_COUNT = %d;\n\n' % (',\n'.join(rows), len(codes)))
    f.write('/* Latin-1, as the module\'s string table has them; codes 128 and up are pieces of physics. */\n')
    f.write('static const char *const EQUATIONS[] = {\n%s\n};\nstatic const int EQUATION_COUNT = %d;\n\n'
            % (',\n'.join('  ' + cstr(s) for s in d['equations']), len(d['equations'])))
    f.write('static const char *const LINES[] = {\n%s\n};\nstatic const int LINE_COUNT = %d;\n\n'
            % (',\n'.join('  ' + cstr(s) for s in d['lines']), len(d['lines'])))
    f.write('}  // namespace art_einstein\n}  // namespace adcore\n')
print('%s: %d glyphs, %d steps' % (a.out, len(codes), len(steps)))
