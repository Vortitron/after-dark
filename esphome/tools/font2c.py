#!/usr/bin/env python3
"""
font2c.py - turns X11 misc-fixed bitmap fonts (public domain) into headers
for ad_font.h, Latin-1 from 0x20 to 0xFF:

    python3 esphome/tools/font2c.py esphome/components/after_dark \
        /usr/share/fonts/X11/misc/{4x6,5x8,6x10,8x13,8x13B,10x20}-ISO8859-1.pcf.gz

Each one becomes ad_font_<WxH[B]>.h holding a Font called font_<WxH[B]>.
"""
import gzip
import io
import os
import re
import sys
import tempfile

from PIL import Image, ImageDraw, ImageFont, PcfFontFile

outdir = sys.argv[1]
for src in sys.argv[2:]:
    m = re.match(r'(\d+)x(\d+)(B?)', os.path.basename(src))
    w, h, bold = int(m.group(1)), int(m.group(2)), m.group(3)
    name = '%dx%d%s' % (w, h, bold)
    raw = gzip.open(src).read() if src.endswith('.gz') else open(src, 'rb').read()
    pcf = PcfFontFile.PcfFontFile(io.BytesIO(raw), 'iso8859-1')
    with tempfile.TemporaryDirectory() as tmp:
        pcf.save(os.path.join(tmp, 'f'))
        font = ImageFont.load(os.path.join(tmp, 'f.pil'))
    stride = (w + 7) // 8
    data = []
    for code in range(0x20, 0x100):
        im = Image.new('1', (w, h), 0)
        ImageDraw.Draw(im).text((0, 0), bytes([code]).decode('latin-1'), font=font, fill=1)
        for y in range(h):
            row = 0
            for x in range(w):
                if im.getpixel((x, y)):
                    row |= 1 << (stride * 8 - 1 - x)
            data += [(row >> (8 * (stride - 1 - i))) & 0xFF for i in range(stride)]
    out = os.path.join(outdir, 'ad_font_%s.h' % name.lower())
    with open(out, 'w') as fh:
        fh.write('// Generated by esphome/tools/font2c.py from X11 misc-fixed %s - do not edit.\n'
                 % os.path.basename(src))
        fh.write('#pragma once\n#include "ad_font.h"\n\nnamespace adcore {\n\n')
        fh.write('inline const uint8_t FONT_%s_BITS[] = {\n' % name.upper())
        per = stride * h
        for i in range(0, len(data), per):
            fh.write('  %s,  // %r\n' % (', '.join('0x%02X' % b for b in data[i:i + per]),
                                         bytes([0x20 + i // per]).decode('latin-1')))
        fh.write('};\n\n/* inline: one copy however many savers use it. */\ninline const Font font_%s = {%d, %d, %d, FONT_%s_BITS};\n\n'
                 % (name.lower(), w, h, stride, name.upper()))
        fh.write('}  // namespace adcore\n')
    print(out)
