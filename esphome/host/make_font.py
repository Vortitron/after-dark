#!/usr/bin/env python3
"""
make_font.py - writes font5x8.h, the character ROM the desktop renderer uses
to draw a simulated character LCD, from X11's misc-fixed 5x8 font:

    python3 esphome/host/make_font.py /usr/share/fonts/X11/misc/5x8.pcf.gz

It is not the HD44780's own ROM, only close to it: what a saver puts in cells
reads the same, but the real panel's letters differ a dot here and there.
"""
import gzip
import io
import os
import sys
import tempfile

from PIL import Image, ImageDraw, ImageFont, PcfFontFile

src = sys.argv[1]
raw = gzip.open(src).read() if src.endswith('.gz') else open(src, 'rb').read()
pcf = PcfFontFile.PcfFontFile(io.BytesIO(raw))
with tempfile.TemporaryDirectory() as tmp:
    pcf.save(os.path.join(tmp, 'f'))
    font = ImageFont.load(os.path.join(tmp, 'f.pil'))

rows = []
for code in range(256):
    bits = [0] * 8
    if 0x20 <= code < 0x7F:
        im = Image.new('1', (5, 8), 0)
        ImageDraw.Draw(im).text((0, 0), chr(code), font=font, fill=1)
        for y in range(8):
            for x in range(5):
                if im.getpixel((x, y)):
                    bits[y] |= 0x10 >> x
    elif code == 0xFF:
        bits = [0x1F] * 8  # the ROM's solid block
    if code == 0xDF:
        bits = [0x1C, 0x14, 0x1C, 0, 0, 0, 0, 0]  # the A00 ROM's degree sign
    if code == ord('.'):
        bits = [0, 0, 0, 0, 0, 0x0C, 0x0C, 0]  # the HD44780's square dot, not X11's little cross
    rows.append(bits)

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'font5x8.h')
with open(out, 'w') as fh:
    fh.write('// Generated by make_font.py from %s - do not edit.\n' % os.path.basename(src))
    fh.write('#pragma once\n#include <cstdint>\n\nstatic const uint8_t FONT5X8[256][8] = {\n')
    for code, bits in enumerate(rows):
        fh.write('  {%s},  // 0x%02X\n' % (', '.join('0x%02X' % b for b in bits), code))
    fh.write('};\n')
print(out)
